// ELSE IF STATEMENT
let grade = 0;

if (grade >= 90) {
  console.log(`You got A+`);
} else if (grade >= 80) {
  console.log(`You scored B+`);
} else if (grade >= 70) {
  console.log(`You scored C+`);
} else if (grade >= 60) {
  console.log(`You scored C`);
} else {
  console.log(`You got F`);
}

